import { Link } from '@tanstack/react-router'

import { useI18n } from '@/lib/i18n'

/**
 * Ссылки на продуктовые страницы — те, что объясняют устройство SolArch
 * и выдают Viewer. Список один на шапку и подвал: следующая такая страница
 * добавляется здесь, и обе точки входа получают её сразу, а не расходятся.
 *
 * Ссылки перечислены явно, а не собраны из массива: `to` у роутера типизирован
 * деревом маршрутов, и явный JSX ловит опечатку в адресе на `tsc`, а не в браузере.
 *
 * Компонент отдаёт только ссылки, без своего `nav`: в шапке они встают внутрь
 * уже существующей навигации, а вложенный `nav` в `nav` — сломанный ландмарк.
 */
export function ProductNav({
  linkClassName,
  activeClassName,
}: {
  linkClassName?: string
  activeClassName?: string
}) {
  const { t } = useI18n()

  return (
    <>
      <Link
        to="/how-it-works"
        className={linkClassName}
        activeProps={{ className: activeClassName }}
      >
        {t.nav.howItWorks}
      </Link>

      {/* Вторая ссылка — `t.nav.viewer` на `/download` — встаёт сюда вместе
          со страницей; ключ для неё уже лежит в обоих словарях. Обе точки входа
          рассчитаны на две ссылки уже сейчас: в шапке группа появляется только
          с `md`, где две помещаются рядом с кабинетом, выходом и переключателями,
          а в подвале они стоят на любой ширине. */}
    </>
  )
}
